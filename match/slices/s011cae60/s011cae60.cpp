// Slice s011cae60 -- OpenSSL 0.9.8g bignum and elliptic-curve internals (lib_cblock).
//
// All twelve functions are the unnamed lib_cblock copy of OpenSSL 0.9.8g code
// that Spore statically linked (see third_party/cblock_resolution.csv, rows for
// these VAs are all "exact-unique").  They come from five upstream translation
// units and are compiled verbatim, as C, exactly like the rest of the vendored
// OpenSSL build:
//
//   crypto/bn/bn_exp2.c   (1)   bn_exp2.cpp
//     011cae60 BN_mod_exp2_mont        -- two-base sliding-window modexp
//
//   crypto/bn/bn_gf2m.c   (2)   bn_gf2m.cpp
//     011cc4d0 BN_GF2m_mod             -- a mod p over GF(2^m), p a BIGNUM
//     011cc7b0 BN_GF2m_mod_mul         -- the same, with a precomputed array
//
//   crypto/ec/ec2_mult.c  (1)   ec2_mult.cpp
//     011cb950 ec_GF2m_montgomery_point_multiply
//
//   crypto/ec/ecp_mont.c  (6)   ecp_mont.cpp
//     011ccc00 ec_GFp_mont_group_set_curve   -- build the BN_MONT_CTX field data
//     011ccd50 ec_GFp_mont_field_mul         -- BN_mod_mul_montgomery
//     011ccda0 ec_GFp_mont_field_sqr         -- BN_mod_mul_montgomery(r,a,a,..)
//     011ccde0 ec_GFp_mont_field_encode      -- BN_mod_mul_montgomery(r,a,RR,..)
//     011cce30 ec_GFp_mont_field_decode      -- BN_from_montgomery
//     011cce70 ec_GFp_mont_field_set_to_one  -- BN_copy(r, mont->one)
//
//   crypto/ec/ecp_nist.c  (2)   ecp_nist.cpp
//     011ccef0 ec_GFp_nist_group_set_curve    -- pick BN_nist_mod_192/224/256/384/521
//     011cd030 ec_GFp_nist_field_mul          -- BN_mul + the picked reducer
//
// Each wrapper #includes the whole upstream .c, because the file-static helpers
// (BN_GF2m_mod_arr/poly2arr, gf2m_Mdouble/Madd/Mxy, BN_nist_mod_*) and the
// per-TU register allocation only come out byte-identical when the entire
// translation unit is present.
//
// Flags: /O2 /arch:SSE /MD /Gy /TC /Iscratch_s011cae60_inc  (see manifest.txt)
// The include link work/match/scratch_s011cae60_inc/ carries the configured
// OpenSSL 0.9.8g headers (crypto/opensslconf.h generated by Configure with
// no-asm no-err no-ocsp no-idea no-bf no-ssl2, plus include/openssl/*).
//
// Equivalence gate (tools/difftest/equiv.py, default inputs): all twelve read
// UNSUPPORTED, e.g. 011cc4d0 "7 unresolved reference(s): _BN_num_bits,
// _CRYPTO_malloc, _CRYPTO_free, _ERR_put_error, _BN_set_word, ..".  The gate
// wants every undefined symbol of the compiled object to have a known original
// VA, and a whole-TU verbatim compile references its sibling OpenSSL functions
// (_BN_mod_mul_montgomery, _BN_MONT_CTX_set, _BN_mul, ..) which are upstream
// headers' declarations, not `// @ 0x..`-annotated ones.  There is no way to
// annotate them without editing the vendored .c, and the failure is structural
// (it names callees of the *other* functions in the TU too).  Byte-exactness is
// proven independently and more strongly by run_all.py --manifest (12/12), and
// byte-equality implies equivalence.  Run it per wrapper with
//   --src match/slices/s011cae60/<wrapper>.cpp
//            --flags "/O2 /arch:SSE /MD /Gy /TC /Iscratch_s011cae60_inc"
//
// No function bodies live in this file.  The VAs and their `// @ 0x...` markers
// are in the five wrapper sources:
//   slices/s011cae60/bn_exp2.cpp
//   slices/s011cae60/bn_gf2m.cpp
//   slices/s011cae60/ec2_mult.cpp
//   slices/s011cae60/ecp_mont.cpp
//   slices/s011cae60/ecp_nist.cpp
