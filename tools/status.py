#!/usr/bin/env python3
"""Project status: per-function coverage at each fidelity tier. Writes docs/STATUS.md."""
import csv, glob, os, re, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = lambda *p: os.path.join(ROOT, *p)

funcs = {}
for f in glob.glob(W("work/decomp_all/index_*.csv")):
    for addr, name, size, status, lines in csv.reader(open(f)):
        funcs[int(addr, 16)] = dict(name=name, size=int(size), status=status)
total = len(funcs)
decomp = sum(1 for v in funcs.values() if v["status"] == "ok")

lib = {}
for f in glob.glob(W("work/oss/*_matches.csv")):
    tag = os.path.basename(f).split("_")[0]
    for r in csv.DictReader(open(f)):
        if r["status"] == "unique":
            lib[int(r["va"], 16)] = (tag, r["name"])
lib_in_funcs = {a: v for a, v in lib.items() if a in funcs}

exact = set()
for line in open(W("match/manifest.txt")):
    p = line.split("#", 1)[0].split()
    if len(p) >= 3:
        exact.add(int(p[2], 16))

named = set()
for line in open(W("symbols/names.txt")):
    p = line.split("#", 1)[0].split()
    if p:
        named.add(int(p[0], 16))
named |= set(lib_in_funcs)

bytes_total = sum(v["size"] for v in funcs.values())
def pct(n, d): return "%.2f%%" % (100.0 * n / d) if d else "-"
by_lib = {}
for tag, _ in lib_in_funcs.values():
    by_lib[tag] = by_lib.get(tag, 0) + 1
lib_bytes = sum(funcs[a]["size"] for a in lib_in_funcs)

out = ["# Status", "",
       "Generated by `tools/status.py`. Counts are functions in the Ghidra project (imports excluded).", "",
       "| Tier | Functions | Share |", "|---|---:|---:|",
       "| Total functions | %d | 100%% |" % total,
       "| T0 raw decompile (Ghidra C) | %d | %s |" % (decomp, pct(decomp, total)),
       "| Named (recovered or library) | %d | %s |" % (len(named & set(funcs)), pct(len(named & set(funcs)), total)),
       "| Library-identified, byte-exact from upstream source | %d | %s (%s of code bytes) |" % (len(lib_in_funcs), pct(len(lib_in_funcs), total), pct(lib_bytes, bytes_total)),
       "| T2 byte-exact, hand-written source | %d | %s |" % (len(exact), pct(len(exact), total)),
       "", "Library breakdown: " + ", ".join("%s %d" % kv for kv in sorted(by_lib.items())), ""]
open(W("docs/STATUS.md"), "w").write("\n".join(out))
print("\n".join(out))
