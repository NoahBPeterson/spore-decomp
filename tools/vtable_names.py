#!/usr/bin/env python3
"""Name virtual methods by matching recovered vtables (work/index/alloc_names.tsv) to ModAPI's
<Class>__vftable structures (SporeGhidra_march2017.xml, GPL-3.0, used as reference data only).

usage: vtable_names.py <image> <modapi xml> <alloc_names.tsv> <out names.txt>
Each slot function gets the declaring class's method name (from the slot's DATATYPE_NAMESPACE),
so inherited implementations are named after the base that declares them.
Slots are only named when the binary's vtable run is at least as long as the declared vftable.
"""
import re, sys, collections
import xml.etree.ElementTree as ET
import pefile

image, xml_path, alloc_tsv, out_path = sys.argv[1:5]
root = ET.parse(xml_path).getroot()
vft = {}   # class short name -> list of (slot, method, declaring class path)
for s in root.iter("STRUCTURE"):
    n = s.get("NAME")
    if n.endswith("__vftable"):
        cls = n[:-len("__vftable")]
        slots = []
        for m in s.iter("MEMBER"):
            ns = m.get("DATATYPE_NAMESPACE", "")
            slots.append((int(m.get("OFFSET"), 16) // 4, m.get("NAME"), ns.replace("/Spore/", "").replace("/", "::")))
        vft.setdefault(cls, slots)
# Classes without their own vftable struct use the type of their first vfptr member.
by_struct = {}
for s_ in root.iter("STRUCTURE"):
    n = s_.get("NAME")
    if n.endswith("__vftable"):
        continue
    for m in s_.iter("MEMBER"):
        if m.get("OFFSET") in ("0x0", "0") and m.get("NAME", "").startswith("_vftable"):
            t = m.get("DATATYPE", "").rstrip(" *")
            if t.endswith("__vftable"):
                by_struct.setdefault(n, t[:-len("__vftable")])
        break
for cls, basecls in by_struct.items():
    if cls not in vft and basecls in vft:
        vft[cls] = vft[basecls]

pe = pefile.PE(image, fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
text = pe.sections[0]
tlo, thi = base + text.VirtualAddress, base + text.VirtualAddress + text.Misc_VirtualSize
def slot(vt, i):
    return pe.get_dword_at_rva(vt - base + 4 * i)
def run_length(vt):
    n = 0
    while tlo <= slot(vt, n) < thi:
        n += 1
    return n

seen = {}
names = collections.OrderedDict()
stats = collections.Counter()
for line in open(alloc_tsv):
    tag, ctor, vt, site = line.rstrip("\n").split("\t")
    if not vt:
        continue
    ns, cls = tag.split("/", 1)
    vt = int(vt, 16)
    if vt in seen:
        continue
    seen[vt] = cls
    names[int(ctor, 16)] = "%s::%s::%s" % (ns, cls, cls)
    names[vt] = "vtbl_%s::%s" % (ns, cls)
    stats["classes"] += 1
    decl = vft.get(cls)
    if not decl:
        stats["no_modapi_decl"] += 1
        continue
    n = run_length(vt)
    if n < len(decl):
        stats["vtable_shorter_than_decl"] += 1
        continue
    stats["classes_named_from_modapi"] += 1
    for i, meth, owner in decl:
        f = slot(vt, i)
        owner = owner or ("%s::%s" % (ns, cls))
        names.setdefault(f, "%s::%s" % (owner, meth))
        stats["slots"] += 1

with open(out_path, "w") as fh:
    fh.write("# Generated by tools/vtable_names.py from allocation tags + ModAPI vftable layouts\n")
    for a, n in names.items():
        n = re.sub(r"[^A-Za-z0-9_:~]", "_", n)
        fh.write("%08x %s  # vt\n" % (a, n))
print(dict(stats), "names:", len(names))
